import AppKit
import ApplicationServices

/// Read selected text and insert text into the frontmost app. Both require Accessibility permission.
@MainActor
enum TextIO {
    struct InsertionTarget {
        let processID: pid_t
        let element: AXUIElement?
        let selection: CFRange?
    }

    static func captureTarget(for app: NSRunningApplication?) -> InsertionTarget? {
        guard let app else { return nil }
        let application = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetMessagingTimeout(application, 0.15)
        var value: CFTypeRef?
        let result = AXUIElementCopyAttributeValue(application, kAXFocusedUIElementAttribute as CFString, &value)
        let element: AXUIElement?
        if result == .success, let value, CFGetTypeID(value) == AXUIElementGetTypeID() {
            element = (value as! AXUIElement)
        } else { element = nil }
        return InsertionTarget(processID: app.processIdentifier, element: element, selection: element.flatMap(selectedRange))
    }

    static func targetIsCurrent(_ target: InsertionTarget?) -> Bool {
        guard let target,
              NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processID,
              let app = NSRunningApplication(processIdentifier: target.processID),
              let current = captureTarget(for: app),
              let originalElement = target.element, let currentElement = current.element,
              CFEqual(originalElement, currentElement) else { return false }
        switch (target.selection, current.selection) {
        case let (.some(a), .some(b)): return a.location == b.location && a.length == b.length
        case (.none, .none): return false
        default: return false
        }
    }

    private static func selectedRange(_ element: AXUIElement) -> CFRange? {
        AXUIElementSetMessagingTimeout(element, 0.15)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(value as! AXValue, .cfRange, &range) else { return nil }
        return range
    }

    private static let vKeyV: CGKeyCode = 9
    private static let vKeyC: CGKeyCode = 8

    /// Read selected text from the focused control through Accessibility. Return nil if unavailable (many Electron apps do not support this).
    static func selectedTextViaAX() -> String? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.25)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        var selected: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &selected) == .success,
              let text = selected as? String else { return nil }
        return text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : text
    }

    /// Try Accessibility first, then simulate ⌘C if needed and restore the clipboard afterward.
    static func selectedText() async -> String? {
        if let text = selectedTextViaAX() { return text }

        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        let before = pasteboard.changeCount
        postKey(vKeyC, flags: .maskCommand)

        var result: String?
        for _ in 0..<20 {
            try? await Task.sleep(for: .milliseconds(25))
            if pasteboard.changeCount != before {
                result = pasteboard.string(forType: .string)
                break
            }
        }
        if pasteboard.changeCount != before { restore(saved, to: pasteboard) }
        guard let result, !result.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return result
    }

    /// Insert text at the cursor using the clipboard and ⌘V, then restore the original clipboard.
    @MainActor
    static func insert(_ text: String) async {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Tell clipboard managers this content is temporary and should not be recorded.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        postKey(vKeyV, flags: .maskCommand)

        try? await Task.sleep(for: .milliseconds(400))
        // Do not overwrite anything the user copied in the meantime.
        if pasteboard.changeCount == ourChange {
            restore(saved, to: pasteboard)
        }
    }

    static func copyToClipboard(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private static func postKey(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .hidSystemState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = flags
        up?.flags = flags
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
